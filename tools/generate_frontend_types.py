def _ts_type(schema: dict, where: str) -> str:
    """Return one schema fragment as a TypeScript type expression; refuse naming ``where``."""
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        # pydantic's JsonValue declares the empty schema: a value carried uninterpreted.
        return "unknown" if name == "JsonValue" else name
    if "anyOf" in schema or "oneOf" in schema:
        return " | ".join(
            dict.fromkeys(
                _ts_type(part, where)
                for part in schema.get("anyOf") or schema["oneOf"]
            )
        )
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        # A one-member Literal renders as ``const``, not ``enum``: its own literal type, the
        # single value TypeScript can narrow the discriminated union on.
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind is None and not schema.keys() - {
        "default",
        "title",
        "description",
    }:
        return "unknown"  # a field carried uninterpreted (``Any``): the backend reads it
    if kind == "null":
        return "null"
    if kind in _PRIMITIVE:
        return _PRIMITIVE[kind]
    if kind == "object":
        # A free-form object (no fixed property set) is the only object shape reached here: a
        # model's own fields arrive as a ``$ref`` instead, so a fixed non-``$ref`` shape refuses.
        if (
            not schema.get("properties")
            and schema.get("additionalProperties") is True
        ):
            return "Record<string, unknown>"
        if not schema.get("properties") and isinstance(
            schema.get("additionalProperties"), dict
        ):
            # dict[str, T] (a typed mapping, not free-form): Record<string, T>.
            return f"Record<string, {_ts_type(schema['additionalProperties'], where)}>"
    if kind == "array":
        if "prefixItems" in schema:
            items = ", ".join(
                _ts_type(s, where) for s in schema["prefixItems"]
            )
            return f"[{items}]"
        if "items" in schema:
            item_schema = schema["items"]
            item_type = _ts_type(item_schema, where)
            # A top-level union (anyOf, or an enum of more than one member) renders bare, with no
            # brackets of its own; parenthesize it so an array of it reads as ``(A | B)[]``.
            if (
                "anyOf" in item_schema
                or "oneOf" in item_schema
                or len(item_schema.get("enum", [])) > 1
            ):
                item_type = f"({item_type})"
            return f"{item_type}[]"
    raise SystemExit(
        f"generate_frontend_types.py cannot map the schema for {where}: {schema}"
    )


def _interface(name: str, schema: dict) -> str:
    """Return one ``export interface`` block for a model's own JSON schema."""
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{\n"]
    for prop, prop_schema in schema.get("properties", {}).items():
        optional = "" if prop in required else "?"
        lines.append(
            f"  {prop}{optional}: {_ts_type(prop_schema, f'{name}.{prop}')};\n"
        )
    if schema.get("additionalProperties") is True:
        # A model keeping undeclared keys as stated (a named block's own values).
        lines.append("  [key: string]: unknown;\n")
    lines.append("}\n")
    return "".join(lines)


def render() -> str:
    """Return the full text of the generated module, formatted."""
    from tcip_mcp.web_client import GUI_STATE_DEFAULTS
    from tcip_web.state import StateSnapshotMessage

    # A model declaring its schema mode (an answer nesting computed fields) renders in it.
    modes: list[tuple[type[BaseModel], JsonSchemaMode]] = [
        (
            m,
            "serialization"
            if getattr(m, "model_config", {}).get("json_schema_mode_override")
            == "serialization"
            else "validation",
        )
        for m in declared_models()
    ]
    refs, combined = models_json_schema(
        [*modes, (StateSnapshotMessage, "serialization")]
    )
    defs = combined["$defs"]
    names = [refs[pair]["$ref"].rsplit("/", 1)[-1] for pair in modes]
    listed = names + list(TRANSPORT_MODELS)
    nested = [n for n in defs if n not in listed and n != "JsonValue"]
    body = "\n".join(_interface(name, defs[name]) for name in names)
    body += "\n" + "\n".join(_interface(name, defs[name]) for name in nested)
    body += "\n" + "\n".join(
        _interface(name, defs[name]) for name in TRANSPORT_MODELS
    )
    defaults = json.dumps(GUI_STATE_DEFAULTS.model_dump(mode="json"))
    body += f"\nexport const GUI_STATE_DEFAULTS: GuiState = {defaults};\n"
    scalars = "".join(
        f"export const {name} = {json.dumps(value)};\n\n"
        for name, value in scalar_constants().items()
    )
    panel_event_names = (
        "".join(
            f"export const {name} = {json.dumps(value)};\n"
            for name, value in platform_panel_event_constants()
        )
        + "\n"
    )
    tuples = "".join(
        f"export const {name} = "
        f"[{', '.join(json.dumps(m) for m in members)}] as const;\n\n"
        for name, members in tuple_constants().items()
    )
    records = "".join(
        f"export const {name}: Record<string, string> = "
        f"{json.dumps(entries)};\n\n"
        for name, entries in record_constants().items()
    )
    aliases = "".join(
        f"export type {name} = {' | '.join(json.dumps(m) for m in members)};\n\n"
        for name, members in literal_aliases().items()
    )
    unions = "".join(
        f"export type {name} = {' | '.join(members)};\n\n"
        for name, members in model_unions().items()
    )
    return formatted(
        HEADER
        + scalars
        + panel_event_names
        + tuples
        + records
        + aliases
        + unions
        + body,
        GENERATED_PATH,
    )


def main() -> int:
    """Write the generated types module and return 0."""
    return write_generated(GENERATED_PATH, render())


if __name__ == "__main__":
    raise SystemExit(main())
