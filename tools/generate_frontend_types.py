class SentSchema(GenerateJsonSchema):
    """A model's schema as it serializes, a field with a default required since it is sent.

    A ``TypedDict`` key that is not required stays optional, since it is sent only when set.
    """

    def field_is_required(
        self,
        field: core_schema.ModelField
        | core_schema.DataclassField
        | core_schema.TypedDictField,
        total: bool,
    ) -> bool:
        """Whether the serialized model always sends ``field``."""
        if field["type"] == "typed-dict-field":
            return super().field_is_required(field, total)
        return field.get("serialization_exclude_if") is None


