"""Generate TypeScript types and constants from the backend's pydantic models and constants.

``routes/images.py`` declares a served image's stats source and the reads a view is served by;
``routes/annotate.py`` the review queue's launch, the scorer block it states
(``tcip_mcp.pipelines.active_learning``) and the job record both its routes answer, and the
engine prompt the canvas sends (the detector's own parameters,
``tcip_mcp.pipelines.proposal_engines``, among it) with its answer, and
``routes/sessions.py`` the annotation timing entries and the sessions they amount to;
``tcip_mcp.experiments`` declares a run's row, a sweep's group, the listing of both and the detail
of one; ``routes/training.py`` and ``routes/terminal.py`` declare their WebSocket frame
vocabularies, and ``routes/terminal.py`` the provider status, the session launch request and
answer, the submitted request, and the session end request and answer;
``routes/projects.py`` declares the project summary and the open, removal, rename and
invariances request shapes, and ``tcip_mcp.project_record`` the capture invariances and their
correction's answer; ``routes/results.py`` declares
the phenology and count export request shapes, the revision confirmation and the registered
models;
``tcip_mcp.traits`` declares the trait record and its revisions; ``tcip_mcp.tools.meta_tools``
the page of a project-memory corpus the meta routes answer; and
``tcip_mcp.web_client.GuiState`` declares the GUI state the backend broadcasts, rendered as the
shape it serializes to, with ``tcip_mcp.web_client.GUI_STATE_DEFAULTS`` as
``GUI_STATE_DEFAULTS``. This script projects them into ``frontend/src/api/types.generated.ts``
through each model's own JSON schema, each interface named as the definition pydantic's schema
refers to it by (a parametrized generic as ``MemoryPage_FrictionReport_``). The mapper covers
only the schema shapes these models use
(string/number/integer/boolean, a nullable union, a nested model by ``$ref``, pydantic's
``JsonValue`` by ``$ref`` rendered as ``unknown``, an array, a fixed-length tuple, a string-enum
union, a single-member ``Literal`` discriminator rendered as its literal type, and a free-form
object (``additionalProperties`` true, no ``properties``) rendered as ``Record<string, unknown>``);
annotation keywords such as ``title`` and ``default`` are ignored rather than mapped, a typed
mapping (``dict[str, T]``, ``additionalProperties`` a schema rather than a bare ``true``) renders
``Record<string, T>``, a model keeping undeclared keys (``extra="allow"``) gains a string index
signature beside its declared fields, and any other shape (including an object with its own
fixed, non-``$ref`` property set) refuses by name.
Each of ``web_client``'s own named ``PANEL_EVENT_*`` constants, the numbers and strings
:func:`scalar_constants` names, and the vocabularies
:func:`tuple_constants` names are projected alongside the models as runtime constants, and those
:func:`literal_aliases` names as bare union types and those :func:`model_unions` names as unions
of the generated interfaces, none of them schema-derived.

Run it after changing a declared model; it rewrites the module in place.
"""

