"""Generate the TypeScript route-path and dev-proxy modules from the backend's routes.

This script emits ``frontend/src/api/routes.ts``: one exported name per path and method of each
route the FastAPI app has registered whose name the frontend's non-test sources read, the reads
``frontend/scripts/routeReads.mjs`` finds through the TypeScript compiler, run under ``node``. It
also emits ``frontend/src/api/devProxy.generated.ts``: one dev-proxy prefix per distinct first
path segment of every registered HTTP or WebSocket route, ``ws`` true wherever a socket is
mounted under it, excluding the paths ``tcip_web.app.FRONTEND_SERVING_PATHS`` names (the app's
own frontend and health routes).

Run it after adding or renaming a route, or after a source adds or drops a ``ROUTES`` read; it
rewrites both modules in place.

    python -m tools.generate_frontend_routes
"""

from __future__ import annotations

import json
import re
import subprocess
from collections.abc import Collection, Iterator
from typing import TYPE_CHECKING, cast

from fastapi.routing import APIRoute, APIWebSocketRoute

from tests import FRONTEND_SRC

if TYPE_CHECKING:
    from fastapi import APIRouter, FastAPI

GENERATED_PATH = FRONTEND_SRC / "api" / "routes.ts"
PROXY_GENERATED_PATH = FRONTEND_SRC / "api" / "devProxy.generated.ts"
READS_SCRIPT = FRONTEND_SRC.parent / "scripts" / "routeReads.mjs"

_PARAM_RE = re.compile(r"\{([^}:]+)")
PRINT_WIDTH = 100

HEADER = """/**
 * The backend routes the frontend's non-test sources read by name, each named for its method and
 * its route.
 *
 * Generated by tools/generate_frontend_routes.py from the routes the FastAPI app registers and
 * the reads scripts/routeReads.mjs finds. Do not edit, and do not write a backend path anywhere
 * else in the frontend. Regenerate after adding or renaming a route, or after a source adds or
 * drops a read of one.
 */

export const ROUTES = {
"""

FOOTER = "} as const;\n"


def _camel(token: str, *, upper_first: bool) -> str:
    """Turn one path segment or parameter name into a TypeScript identifier fragment."""
    words = [w for w in re.split(r"[^0-9a-zA-Z]+", token) if w]
    if not words:
        return ""
    head = words[0]
    head = head.capitalize() if upper_first else head[0].lower() + head[1:]
    return head + "".join(w.capitalize() for w in words[1:])


def route_name(path: str, method: str) -> str:
    """Return the exported name for one (path, method): method, then segments, then params."""
    prefix = "socket" if method == "WEBSOCKET" else method.lower()
    segments = [s for s in path.strip("/").split("/") if s]
    if segments and segments[0] == "api":
        segments = segments[1:]
    parts = []
    for segment in segments:
        if segment.startswith("{"):
            match = _PARAM_RE.match(segment)
            assert match is not None, (
                f"malformed path parameter segment {segment!r}"
            )
            parts.append("By" + _camel(match.group(1), upper_first=True))
        else:
            parts.append(_camel(segment, upper_first=True))
    return prefix + ("".join(parts) or "Root")


def iter_api_routes(
    app: FastAPI | APIRouter,
) -> Iterator[APIRoute | APIWebSocketRoute]:
    """Yield every ``APIRoute``/``APIWebSocketRoute`` the app has actually registered.

    Routers are included through wrapper objects rather than flattened onto the app, so this
    descends into whatever a registered entry carries its own routes under.
    """
    for route in app.routes:
        if isinstance(route, (APIRoute, APIWebSocketRoute)):
            yield route
        elif hasattr(route, "original_router"):
            yield from iter_api_routes(route.original_router)


def collect_routes(app: FastAPI) -> list[tuple[str, str, str]]:
    """Return every (name, path, method) the app has registered, sorted by name."""
    found: list[tuple[str, str, str]] = []
    for route in iter_api_routes(app):
        if isinstance(route, APIRoute):
            # Starlette types methods optional; FastAPI's own route construction always sets it.
            methods = cast("set[str]", route.methods)
            for method in sorted(methods - {"HEAD", "OPTIONS"}):
                found.append(
                    (route_name(route.path, method), route.path, method)
                )
        else:
            found.append(
                (route_name(route.path, "WEBSOCKET"), route.path, "WEBSOCKET")
            )

    by_name: dict[str, tuple[str, str, str]] = {}
    for entry in found:
        clash = by_name.get(entry[0])
        if clash is not None:
            raise SystemExit(
                f"two routes generate the name {entry[0]!r}: "
                f"{clash[2]} {clash[1]} and {entry[2]} {entry[1]}"
            )
        by_name[entry[0]] = entry
    return sorted(by_name.values())


def _entry(name: str, path: str) -> str:
    """Return one ROUTES member: a plain string, or an arrow taking the path's parameters."""
    params = _PARAM_RE.findall(path)
    if not params:
        return f'  {name}: "{path}",\n'
    args = ", ".join(f"{_camel(p, upper_first=False)}: string" for p in params)
    body = re.sub(
        r"\{([^}:]+)(?::[^}]*)?\}",
        lambda m: (
            "${encodeURIComponent("
            + _camel(m.group(1), upper_first=False)
            + ")}"
        ),
        path,
    )
    single = f"  {name}: ({args}) => `{body}`,\n"
    if len(single) - 1 <= PRINT_WIDTH:
        return single
    return f"  {name}: ({args}) =>\n    `{body}`,\n"


def read_routes(
    app: FastAPI, names: Collection[str]
) -> list[tuple[str, str, str]]:
    """Return each (name, path, method) of :func:`collect_routes` whose name is in ``names``.

    Refuses, naming them, the names no registered route generates.
    """
    routes = [route for route in collect_routes(app) if route[0] in names]
    unknown = sorted(set(names) - {name for name, _, _ in routes})
    if unknown:
        raise SystemExit(
            f"the frontend reads routes the backend does not register: {unknown}"
        )
    return routes


def render(app: FastAPI, names: Collection[str]) -> str:
    """Return the full text of the generated module over :func:`read_routes` of ``names``."""
    return (
        HEADER
        + "".join(
            _entry(name, path) for name, path, _ in read_routes(app, names)
        )
        + FOOTER
    )


def collect_proxy_entries(app: FastAPI) -> list[tuple[str, bool]]:
    """Return one dev-proxy prefix per distinct first path segment of a registered route, sorted.

    Each is paired with whether a websocket is mounted under it. Excludes the paths
    ``tcip_web.app.FRONTEND_SERVING_PATHS`` names: the app's own frontend and health routes.
    """
    from tcip_web.app import FRONTEND_SERVING_PATHS

    ws_by_prefix: dict[str, bool] = {}
    for _name, path, method in collect_routes(app):
        if path in FRONTEND_SERVING_PATHS:
            continue
        segments = [s for s in path.strip("/").split("/") if s]
        if not segments:
            continue
        prefix = "/" + segments[0]
        ws_by_prefix[prefix] = (
            ws_by_prefix.get(prefix, False) or method == "WEBSOCKET"
        )
    return sorted(ws_by_prefix.items())


PROXY_HEADER = """/**
 * Dev-server proxy prefixes, generated by tools/generate_frontend_routes.py from the routes
 * the FastAPI app registers. Do not edit; vite.config.ts pairs each with the backend target.
 */

export interface DevProxyEntry {
  path: string;
  ws: boolean;
}

export const DEV_PROXY: DevProxyEntry[] = [
"""

PROXY_FOOTER = "];\n"


def render_proxy(app: FastAPI) -> str:
    """Return the full text of the generated dev-proxy module.

    The module also carries the loopback host the backend binds and answers to
    (``tcip_mcp.web_client.LOOPBACK_HOST``).
    """
    from tcip_mcp.web_client import LOOPBACK_HOST

    body = "".join(
        f'  {{ path: "{path}", ws: {str(ws).lower()} }},\n'
        for path, ws in collect_proxy_entries(app)
    )
    return (
        PROXY_HEADER
        + body
        + PROXY_FOOTER
        + f'\nexport const LOOPBACK_HOST = "{LOOPBACK_HOST}";\n'
    )


def frontend_reads() -> dict:
    """Return what :data:`READS_SCRIPT`, run under ``node``, prints over :data:`FRONTEND_SRC`.

    That is the frontend's non-test ``sources``, the route names they ``reads``, and their
    backend path ``literals``, each a ``file`` and its ``text``.
    """
    printed = subprocess.run(
        ["node", str(READS_SCRIPT), str(FRONTEND_SRC)],
        capture_output=True,
        text=True,
        check=True,
    )
    return json.loads(printed.stdout)


def main() -> int:
    """Write the route module and the dev-proxy module from the app's routes; return 0.

    The names rendered are the :func:`frontend_reads` ``reads``.
    """
    from tcip_web.app import app

    GENERATED_PATH.write_text(
        render(app, frontend_reads()["reads"]), encoding="utf-8", newline="\n"
    )
    print(f"wrote {GENERATED_PATH}")
    PROXY_GENERATED_PATH.write_text(
        render_proxy(app), encoding="utf-8", newline="\n"
    )
    print(f"wrote {PROXY_GENERATED_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
