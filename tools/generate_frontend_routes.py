"""Generate the TypeScript route-path and dev-proxy modules from the backend's routes.

This script emits the route module at :data:`GENERATED_PATH`: one exported name per path and
method of each route the FastAPI app has registered whose name the frontend's non-test sources
read, the reads ``tests.READS_SCRIPT`` finds through the TypeScript compiler, run under ``node``. A
path parameter is typed by the alias ``tools/generate_frontend_types.py`` generates for its
declared ``Literal`` vocabulary, and ``string`` where it is declared ``str``. It also emits the
dev-proxy module at :data:`PROXY_GENERATED_PATH`: one dev-proxy prefix per distinct first path
segment of every registered HTTP or WebSocket route, ``ws`` true wherever a socket is mounted
under it, excluding the paths ``tcip_web.app.FRONTEND_SERVING_PATHS`` names (the app's own
frontend and health routes), with the backend's loopback host and default port. The routes are
FastAPI's effective route contexts, and both modules are formatted by the frontend's installed
Prettier under its own configuration.

Run it after adding or renaming a route, or after a source adds or drops a ``ROUTES`` read; it
rewrites both modules in place.

    python -m tools.generate_frontend_routes
"""

from __future__ import annotations

import json
import re
from collections.abc import Collection
from string import Formatter
from typing import TYPE_CHECKING, Any, cast, get_args

from fastapi.routing import (
    APIRoute,
    APIWebSocketRoute,
    RouteContext,
    iter_route_contexts,
)

from tests import (
    FRONTEND_SRC,
    READS_SCRIPT,
    formatted,
    printed_json,
    write_generated,
)
from tools.generate_frontend_types import (
    GENERATED_PATH as TYPES_PATH,
    literal_aliases,
)

if TYPE_CHECKING:
    from fastapi import FastAPI

GENERATED_PATH = FRONTEND_SRC / "api" / "routes.ts"
PROXY_GENERATED_PATH = FRONTEND_SRC / "api" / "devProxy.generated.ts"

HEADER = """/**
 * The backend routes the frontend's non-test sources read by name, each named for its method and
 * its route.
 *
 * Generated by tools/generate_frontend_routes.py from the routes the FastAPI app registers and
 * the sources' reads. Do not edit.
 */

"""

FOOTER = "} as const;\n"


def _camel(token: str, *, upper_first: bool) -> str:
    """Turn one path segment or parameter name into a TypeScript identifier fragment."""
    words = [w for w in re.split(r"[^0-9a-zA-Z]+", token) if w]
    if not words:
        return ""
    head = words[0]
    head = head.capitalize() if upper_first else head[0].lower() + head[1:]
    return head + "".join(w.capitalize() for w in words[1:])


def route_name(path: str, method: str) -> str:
    """Return the exported name for one (path, method): method, then segments, then params.

    ``path`` is a route's path format, each parameter named in it read as ``By<Param>``.
    """
    prefix = "socket" if method == "WEBSOCKET" else method.lower()
    segments = path.strip("/").split("/")
    if segments[0] == "api":
        segments = segments[1:]
    parts = [
        _camel(literal, upper_first=True)
        + ("" if param is None else "By" + _camel(param, upper_first=True))
        for segment in segments
        for literal, param, _, _ in Formatter().parse(segment)
    ]
    return prefix + ("".join(parts) or "Root")


def api_route_contexts(app: FastAPI) -> list[RouteContext]:
    """Return FastAPI's effective context of each HTTP and WebSocket API route of ``app``.

    Each carries the route's path under every include prefix, its methods, name, path format,
    parameter convertors, endpoint and dependant.
    """
    contexts = []
    for context in iter_route_contexts(app.routes):
        if isinstance(context.original_route, (APIRoute, APIWebSocketRoute)):
            # FastAPI states an included socket's prefixed route on starlette_route alone.
            included = getattr(context, "starlette_route", None)
            contexts.append(
                context if included is None else RouteContext(included)
            )
    return contexts


def collect_routes(app: FastAPI) -> list[tuple[str, str, str, dict[str, Any]]]:
    """Return every (name, path, method, parameters) the app registers, sorted by name.

    The path is the route's path format under every include prefix, and the parameters are its
    path parameters' declared annotations by name. Refuses a name two routes generate.
    """
    by_name: dict[str, tuple[str, str, str, dict[str, Any]]] = {}
    for context in api_route_contexts(app):
        # RouteContext types each field optional; an API route's context always carries it.
        path = cast("str", context.path_format)
        methods = (
            {"WEBSOCKET"}
            if isinstance(context.original_route, APIWebSocketRoute)
            else cast("set[str]", context.methods) - {"HEAD", "OPTIONS"}
        )
        parameters = {
            field.name: field.field_info.annotation
            for field in context.dependant.path_params
        }
        for method in sorted(methods):
            name = route_name(path, method)
            clash = by_name.get(name)
            if clash is not None:
                raise SystemExit(
                    f"two routes generate the name {name!r}: "
                    f"{clash[2]} {clash[1]} and {method} {path}"
                )
            by_name[name] = (name, path, method, parameters)
    return [by_name[name] for name in sorted(by_name)]


def _entry(name: str, path: str, types: dict[str, str]) -> str:
    """Return one ROUTES member: the path, or an arrow taking its parameters, typed by ``types``."""
    pieces = list(Formatter().parse(path))
    params = [param for _, param, _, _ in pieces if param is not None]
    if not params:
        return f"  {name}: {json.dumps(path)},\n"
    args = ", ".join(
        f"{_camel(param, upper_first=False)}: {types[param]}"
        for param in params
    )
    body = "".join(
        literal
        if param is None
        else f"{literal}${{encodeURIComponent({_camel(param, upper_first=False)})}}"
        for literal, param, _, _ in pieces
    )
    return f"  {name}: ({args}) => `{body}`,\n"


def read_routes(
    app: FastAPI, names: Collection[str]
) -> list[tuple[str, str, str, dict[str, Any]]]:
    """Return each route of :func:`collect_routes` whose name is in ``names``.

    Refuses, naming them, the names no registered route generates.
    """
    routes = [route for route in collect_routes(app) if route[0] in names]
    unknown = sorted(set(names) - {route[0] for route in routes})
    if unknown:
        raise SystemExit(
            f"the frontend reads routes the backend does not register: {unknown}"
        )
    return routes


def render(app: FastAPI, names: Collection[str]) -> str:
    """Return the generated module over :func:`read_routes` of ``names``, formatted.

    A parameter declared ``str`` is typed ``string``, and one declared as a ``Literal``
    vocabulary by the alias :func:`literal_aliases` names, which the module imports from the
    generated types module.
    """
    aliases = {members: alias for alias, members in literal_aliases().items()}
    entries = [
        (
            name,
            path,
            {
                param: "string"
                if declared is str
                else aliases[get_args(declared)]
                for param, declared in parameters.items()
            },
        )
        for name, path, _, parameters in read_routes(app, names)
    ]
    named = sorted(
        {t for _, _, types in entries for t in types.values()}
        & set(aliases.values())
    )
    module = TYPES_PATH.relative_to(GENERATED_PATH.parent).with_suffix("")
    imports = (
        f'import type {{ {", ".join(named)} }} from "./{module.as_posix()}";\n\n'
        if named
        else ""
    )
    return formatted(
        HEADER
        + imports
        + "export const ROUTES = {\n"
        + "".join(_entry(*entry) for entry in entries)
        + FOOTER,
        GENERATED_PATH,
    )


def collect_proxy_entries(app: FastAPI) -> list[tuple[str, bool]]:
    """Return one dev-proxy prefix per distinct first path segment of a registered route, sorted.

    Each is paired with whether a websocket is mounted under it. Excludes the paths
    ``tcip_web.app.FRONTEND_SERVING_PATHS`` names: the app's own frontend and health routes.
    """
    from tcip_web.app import FRONTEND_SERVING_PATHS

    ws_by_prefix: dict[str, bool] = {}
    for _name, path, method, _ in collect_routes(app):
        if path in FRONTEND_SERVING_PATHS:
            continue
        segments = [s for s in path.strip("/").split("/") if s]
        if not segments:
            continue
        prefix = "/" + segments[0]
        ws_by_prefix[prefix] = (
            ws_by_prefix.get(prefix, False) or method == "WEBSOCKET"
        )
    return sorted(ws_by_prefix.items())


PROXY_HEADER = """/**
 * Dev-server proxy prefixes from the routes the FastAPI app registers, and the backend's loopback
 * host and default port, generated by tools/generate_frontend_routes.py. Do not edit.
 */

export interface DevProxyEntry {
  path: string;
  ws: boolean;
}

export const DEV_PROXY: DevProxyEntry[] = [
"""

PROXY_FOOTER = "];\n"


def render_proxy(app: FastAPI) -> str:
    """Return the generated dev-proxy module, formatted.

    The module also carries the loopback host the backend binds and answers to
    (``tcip_mcp.web_client.LOOPBACK_HOST``) and the port it asks for by default
    (``tcip_web.__main__.DEFAULT_PORT``).
    """
    from tcip_mcp.web_client import LOOPBACK_HOST
    from tcip_web.__main__ import DEFAULT_PORT

    body = "".join(
        f"  {{ path: {json.dumps(path)}, ws: {json.dumps(ws)} }},\n"
        for path, ws in collect_proxy_entries(app)
    )
    return formatted(
        PROXY_HEADER
        + body
        + PROXY_FOOTER
        + f"\nexport const LOOPBACK_HOST = {json.dumps(LOOPBACK_HOST)};\n"
        + f"\nexport const BACKEND_PORT = {DEFAULT_PORT};\n",
        PROXY_GENERATED_PATH,
    )


def frontend_reads() -> dict:
    """Return what ``tests.READS_SCRIPT`` prints over ``tests.FRONTEND_SRC``.

    That is the frontend's non-test ``sources``, the route names they ``reads``, their backend
    path ``literals``, each a ``file`` and its ``text``, and their declared ``shapes``,
    string literal ``unions`` and exported string ``constants``.
    """
    return printed_json(READS_SCRIPT, FRONTEND_SRC)


def main() -> int:
    """Write the route module and the dev-proxy module from the app's routes; return 0.

    The names rendered are the :func:`frontend_reads` ``reads``.
    """
    from tcip_web.app import app

    write_generated(GENERATED_PATH, render(app, frontend_reads()["reads"]))
    return write_generated(PROXY_GENERATED_PATH, render_proxy(app))


if __name__ == "__main__":
    raise SystemExit(main())
